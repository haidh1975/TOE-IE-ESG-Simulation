def _simple_slope(fit, xvar, modvar, dv_label, ax, title):
    """Plot dv on xvar at +/-1 SD of the moderator, using fitted coefficients."""
    b_x = fit.params[xvar]
    inter = [v for v in fit.params.index if "_x_" in v and xvar in v]
    b_i = fit.params[inter[0]] if inter else 0.0
    xs = np.linspace(-2, 2, 50)
    for lvl, lab, ls in [(-1, "Low moderator (-1 SD)", "-"),
                         (+1, "High moderator (+1 SD)", "--")]:
        ax.plot(xs, (b_x + b_i * lvl) * xs, ls, label=lab, linewidth=2)
    ax.axhline(0, color="grey", linewidth=.6)
    ax.axvline(0, color="grey", linewidth=.6)
    ax.set_xlabel("ESG performance (standardized)")
    ax.set_ylabel(dv_label)
    ax.set_title(title, fontsize=10)
    ax.legend(fontsize=8)


