def build_dataset(n=500, seed=42, coefs=None):
    """
    Generate the calibrated reference dataset.
    Returns standardized construct scores. These ARE the analysis variables
    (see FIX 1). Item indicators are produced by generate_item_matrix().
    """
    C = dict(TARGETS) if coefs is None else dict(coefs)
    rng = np.random.default_rng(seed)

    def tnorm(mu, sd, lo, hi):
        a, b = (lo - mu) / sd, (hi - mu) / sd
        return stats.truncnorm(a, b, loc=mu, scale=sd).rvs(size=n, random_state=rng)

    # --- Step 1. Exogenous constructs
    ESG    = tnorm(4.24, 0.65, 1.0, 9.0)
    Myopia = np.abs(rng.normal(0, 0.091, n)).clip(0.010, 0.400)
    IndivF = tnorm(3.09, 0.87, 1.0, 5.0)
    OrgF   = tnorm(3.20, 0.80, 1.0, 5.0)
    TechF  = tnorm(3.15, 0.82, 1.0, 5.0)
    EnvF   = tnorm(3.05, 0.85, 1.0, 5.0)

    lnSize   = rng.normal(3.50, 0.80, n)
    Age      = rng.gamma(shape=2.0, scale=8.0, size=n)
    ROA      = rng.normal(0.045, 0.060, n)
    Leverage = rng.beta(2.0, 3.0, n)

    # --- Step 2. Financing Constraints  [FIX 2 + FIX 3]
    SA = -0.737 * lnSize + 0.043 * lnSize**2 - 0.040 * Age
    FC = (C["FC_SAindex"] * z(SA)
          + C["FC_ESG"] * z(ESG)
          + rng.normal(0, SIGMA["FC"], n))

    # --- Step 3. Standardize
    esg, myo, ind = z(ESG), z(Myopia), z(IndivF)
    org, tec, env = z(OrgF), z(TechF), z(EnvF)
    fc = z(FC)
    lns, age = z(lnSize), z(Age)
    roa, lev = z(ROA), z(Leverage)
    esg_myo = z(esg * myo)
    esg_ind = z(esg * ind)

    # --- Step 4. Endogenous constructs
    SubstDig = (C["SD_ESG"]*esg + C["SD_Myopia"]*myo + C["SD_IndivF"]*ind
                + C["SD_OrgF"]*org + C["SD_TechF"]*tec + C["SD_EnvF"]*env
                + C["SD_FC"]*fc
                + C["SD_ESGxMyopia"]*esg_myo + C["SD_ESGxIndivF"]*esg_ind
                + C["SD_lnSize"]*lns + C["SD_Age"]*age
                + C["SD_ROA"]*roa + C["SD_Leverage"]*lev
                + rng.normal(0, SIGMA["SubstDig"], n))

    StratDig = (C["StD_ESG"]*esg + C["StD_Myopia"]*myo + C["StD_IndivF"]*ind
                + C["StD_ESGxMyopia"]*esg_myo
                + rng.normal(0, SIGMA["StratDig"], n))

    OpPerf = (C["OP_SubstDig"]*z(SubstDig) + C["OP_StratDig"]*z(StratDig)
              + C["OP_IndivF"]*ind
              + rng.normal(0, SIGMA["OpPerf"], n))

    return pd.DataFrame({
        "ESG": esg, "Myopia": myo, "IndivF": ind, "OrgF": org,
        "TechF": tec, "EnvF": env, "FC": fc,
        "SubstDig": z(SubstDig), "StratDig": z(StratDig), "OpPerf": z(OpPerf),
        "ESG_x_Myopia": esg_myo, "ESG_x_IndivF": esg_ind,
        "lnSize": lns, "Age": age, "ROA": roa, "Leverage": lev,
        "SA_index": z(SA),
    })


def generate_item_matrix(df, seed=42):
    """
    [FIX 1] Measurement layer, used ONLY for the calibration check.
    NOT used in any regression.
    """
    rng = np.random.default_rng(seed + 7)
    items = {}
    for c, spec in ITEM_SPEC.items():
        lam, k = spec["loading"], spec["n_items"]
        L = df[c].values
        items[c] = np.column_stack([
            lam * L + np.sqrt(1 - lam**2) * rng.normal(0, 1, len(L))
            for _ in range(k)
        ])
    return items


