def cronbach_alpha(X):
    k = X.shape[1]
    return (k / (k - 1)) * (1 - X.var(axis=0, ddof=1).sum() / X.sum(axis=1).var(ddof=1))


def measurement_check(items):
    """Alpha, CR, AVE from the ACTUAL generated item matrix. [FIX 5]"""
    rows = []
    for c, X in items.items():
        k = X.shape[1]
        loadings = np.array([ITEM_SPEC[c]["loading"]] * k)
        ave = float((loadings**2).mean())
        s = loadings.sum()
        cr = float(s**2 / (s**2 + (1 - loadings**2).sum()))
        a = float(cronbach_alpha(X))
        rows.append({
            "Construct": c, "Items": k,
            "Mean loading": round(float(loadings.mean()), 3),
            "Cronbach alpha": round(a, 3),
            "CR": round(cr, 3),
            "AVE": round(ave, 3),
            "alpha>=.70": "Yes" if a >= .70 else "NO",
            "CR>=.70": "Yes" if cr >= .70 else "NO",
            "AVE>=.50": "Yes" if ave >= .50 else "NO",
        })
    return pd.DataFrame(rows)


def htmt_matrix(items):
    """[FIX 4] Heterotrait-monotrait ratio from item-level data."""
    names = list(items.keys())
    M = pd.DataFrame(np.nan, index=names, columns=names, dtype=float)

    def mono(X):
        k = X.shape[1]
        return np.mean([np.corrcoef(X[:, p], X[:, q])[0, 1]
                        for p in range(k) for q in range(p + 1, k)])

    for i, aa in enumerate(names):
        for j, bb in enumerate(names):
            if i >= j:
                continue
            Xa, Xb = items[aa], items[bb]
            hetero = np.mean([[np.corrcoef(Xa[:, p], Xb[:, q])[0, 1]
                               for q in range(Xb.shape[1])]
                              for p in range(Xa.shape[1])])
            M.loc[aa, bb] = round(float(hetero / np.sqrt(mono(Xa) * mono(Xb))), 3)
    return M


