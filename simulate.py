def ols_report(fits):
    L = ["=" * 78,
         "OLS RESULTS - TOE-IE-ESG CALIBRATION ILLUSTRATION (v2.0 AUTHORITATIVE)",
         "HC3 heteroskedasticity-robust standard errors.",
         "All variables standardized (mean 0, SD 1).",
         "Outputs are illustrative, NOT empirical confirmation.",
         "=" * 78]
    for k, r in fits.items():
        L += ["", "-" * 78, f"  {k}",
              f"  N={int(r.nobs)}   R2={r.rsquared:.3f}   adj-R2={r.rsquared_adj:.3f}",
              "-" * 78,
              f"  {'Variable':<18}{'beta':>9}{'SE':>9}{'t':>8}{'p':>9}  sig"]
        for v in r.params.index:
            b, se, t, p = r.params[v], r.bse[v], r.tvalues[v], r.pvalues[v]
            s = ("***" if p < .001 else "**" if p < .01 else
                 "*" if p < .05 else "+" if p < .10 else "")
            L.append(f"  {v:<18}{b:>9.3f}{se:>9.3f}{t:>8.2f}{p:>9.4f}  {s}")
    L += ["", "=" * 78, "*** p<.001  ** p<.01  * p<.05  + p<.10"]
    return "\n".join(L)



