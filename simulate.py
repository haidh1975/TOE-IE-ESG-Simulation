FOCAL = {
    "H1a": ("M2_SubstDig_moderation", "ESG",          "SD_ESG"),
    "H1b": ("M3_StratDig_moderation", "ESG",          "StD_ESG"),
    "H1c": ("M5a_FC_on_ESG",          "ESG",          "FC_ESG"),
    "H2":  ("M4_OpPerf",              "SubstDig",     "OP_SubstDig"),
    "H3a": ("M2_SubstDig_moderation", "ESG_x_Myopia", "SD_ESGxMyopia"),
    "H3b": ("M3_StratDig_moderation", "ESG_x_Myopia", "StD_ESGxMyopia"),
    "H4":  ("M2_SubstDig_moderation", "ESG_x_IndivF", "SD_ESGxIndivF"),
}
_FOCAL_MODELS = {v[0] for v in FOCAL.values()}


def monte_carlo(n=500, reps=1000, seed=42, perturb=0.20):
    """Each coefficient perturbed INDEPENDENTLY; reports power/bias/RMSE/coverage."""
    rng = np.random.default_rng(seed + 5000)
    acc = {h: {"b": [], "sig": [], "cov": [], "tgt": []} for h in FOCAL}
    for r in range(reps):
        C = {k: v * rng.uniform(1 - perturb, 1 + perturb) for k, v in TARGETS.items()}
        d = build_dataset(n=n, seed=seed + r + 1, coefs=C)
        fits = {k: smf.ols(MODELS[k], data=d).fit(cov_type="HC3")
                for k in _FOCAL_MODELS}
        for h, (mk, var, tkey) in FOCAL.items():
            res = fits[mk]
            b, p = float(res.params[var]), float(res.pvalues[var])
            ci = res.conf_int().loc[var]
            tgt = C[tkey]
            acc[h]["b"].append(b)
            acc[h]["sig"].append(p < .05)
            acc[h]["cov"].append(bool(ci.iloc[0] <= tgt <= ci.iloc[1]))
            acc[h]["tgt"].append(tgt)
    rows = []
    for h, a in acc.items():
        b = np.array(a["b"]); t = np.array(a["tgt"])
        rows.append({"Hypothesis": h,
                     "Imposed (mean)": round(float(t.mean()), 3),
                     "Recovered (mean)": round(float(b.mean()), 3),
                     "Bias": round(float((b - t).mean()), 3),
                     "RMSE": round(float(np.sqrt(((b - t)**2).mean())), 3),
                     "Empirical power": round(float(np.mean(a["sig"])), 3),
                     "95% CI coverage": round(float(np.mean(a["cov"])), 3)})
    return pd.DataFrame(rows)


def power_curve(sizes=(250, 500, 1000, 2000, 4000), reps=300, seed=42):
    rows = []
    for n in sizes:
        acc = {h: [] for h in FOCAL}
        for r in range(reps):
            d = build_dataset(n=n, seed=seed + 90000 + r)
            fits = {k: smf.ols(MODELS[k], data=d).fit(cov_type="HC3")
                    for k in _FOCAL_MODELS}
            for h, (mk, var, _) in FOCAL.items():
                acc[h].append(float(fits[mk].pvalues[var]) < .05)
        row = {"n": n}
        row.update({h: round(float(np.mean(v)), 3) for h, v in acc.items()})
        rows.append(row)
    return pd.DataFrame(rows)


