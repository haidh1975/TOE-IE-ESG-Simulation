def fit_models(df):
    """All models use HC3 heteroskedasticity-robust standard errors. [FIX 8]"""
    return {k: smf.ols(f, data=df).fit(cov_type="HC3") for k, f in MODELS.items()}


def bootstrap_indirect(df, n_boot=5000, seed=42):
    """[FIX 2] Direct bootstrap of ESG -> FC -> SubstDig."""
    rng = np.random.default_rng(seed)
    idx = np.arange(len(df))
    out = np.empty(n_boot)
    for b in range(n_boot):
        d = df.iloc[rng.choice(idx, len(df), replace=True)]
        aa = smf.ols("FC ~ ESG + SA_index + ROA + Leverage", data=d).fit().params["ESG"]
        bb = smf.ols(f"SubstDig ~ ESG + FC + IndivF + OrgF + {CONTROLS}",
                     data=d).fit().params["FC"]
        out[b] = aa * bb
    lo, hi = np.percentile(out, [2.5, 97.5])
    return {"indirect": float(out.mean()), "ci_low": float(lo),
            "ci_high": float(hi), "excludes_zero": bool(lo > 0 or hi < 0)}


